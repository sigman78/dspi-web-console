// Generates src/protocol/paged.gen.ts from the firmware's paged command
// registry, vendored byte-for-byte in src/protocol/vendor/ at the commit named
// in SOURCE.json.
//
// Usage:
//   node scripts/gen-paged.mjs              regenerate from the vendored files
//   node scripts/gen-paged.mjs --check      exit 1 if paged.gen.ts is stale
//   node scripts/gen-paged.mjs --fetch SHA  re-vendor from WeebLabs/DSPi at SHA, then regenerate

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const VENDOR = resolve(ROOT, 'src/protocol/vendor');
const OUT = resolve(ROOT, 'src/protocol/paged.gen.ts');
const REPO = 'WeebLabs/DSPi';
const FILES = ['dspi_commands.json', 'legacy_map.json'];

function fail(msg) {
  console.error(`gen-paged: ${msg}`);
  process.exit(1);
}

// Downloads and validates both files before writing any, so a failed fetch
// leaves the vendored set untouched.
async function vendor(sha) {
  if (!/^[0-9a-f]{40}$/.test(sha)) fail('--fetch needs a full 40-character commit SHA');
  const bodies = [];
  for (const file of FILES) {
    const url = `https://raw.githubusercontent.com/${REPO}/${sha}/Documentation/protocol/${file}`;
    const res = await fetch(url);
    if (!res.ok) fail(`${url}: HTTP ${res.status}`);
    bodies.push(Buffer.from(await res.arrayBuffer()));
  }
  const [registry, legacy] = bodies.map((b, i) => {
    try { return JSON.parse(b.toString('utf8')); } catch (err) { return fail(`${FILES[i]}: ${err.message}`); }
  });
  validate(registry, legacy);
  FILES.forEach((file, i) => writeFileSync(resolve(VENDOR, file), bodies[i]));
  const source = { repo: REPO, sha, path: 'Documentation/protocol', files: FILES };
  writeFileSync(resolve(VENDOR, 'SOURCE.json'), `${JSON.stringify(source, null, 2)}\n`);
}

const hex = (n, width) => `0x${n.toString(16).toUpperCase().padStart(width, '0')}`;
const str = (s) => {
  if (!/^[\w.-]*$/.test(s)) fail(`unexpected characters in token ${JSON.stringify(s)}`);
  return `'${s}'`;
};
const docComment = (s, indent) => (s ? `${indent}/** ${s.replace(/\*\//g, '* /')} */\n` : '');

const IDENT = /^[A-Z_][A-Z0-9_]*$/;

function validate(registry, legacy) {
  const seen = new Set();
  for (const page of registry.pages) {
    if (!IDENT.test(page.mnemonic)) fail(`page mnemonic ${JSON.stringify(page.mnemonic)} is not an identifier`);
    if (!(page.page >= 1 && page.page <= 0xFF)) fail(`page ${page.mnemonic}: number ${page.page} is outside 1..255`);
    if (legacy.pages[page.mnemonic] !== page.page) fail(`page ${page.mnemonic} differs between the registry and legacy_map`);
    for (const c of page.commands) {
      if (!IDENT.test(c.name)) fail(`${page.mnemonic}: command name ${JSON.stringify(c.name)} is not an identifier`);
      if (!(c.cmd >= 0 && c.cmd <= 0xFF)) fail(`${page.mnemonic}.${c.name}: cmd ${c.cmd} is outside 0..255`);
      if (!c.get && !c.set) fail(`${page.mnemonic}.${c.name}: neither GET nor SET`);
      if (c.id !== ((page.page << 8) | c.cmd)) fail(`${page.mnemonic}.${c.name}: id ${c.id} is not page << 8 | cmd`);
      if (seen.has(c.id)) fail(`duplicate command id ${hex(c.id, 4)}`);
      seen.add(c.id);
    }
  }
}

function render(registry, legacy, source) {
  const commands = registry.pages.flatMap((p) => p.commands);
  const addrs = [...new Set(commands.map((c) => c.addr))].sort();
  const flags = [...new Set(commands.flatMap((c) => c.flags))].sort();
  const union = (xs) => (xs.length ? xs.map(str).join(' | ') : 'never');

  let out = '';
  out += `// Generated by scripts/gen-paged.mjs from ${source.repo} ${source.path}\n`;
  out += `// at ${source.sha}. Do not edit; run \`npm run gen:paged\`.\n\n`;
  out += `export const PROTOCOL_MAJOR = ${registry.protocol.major};\n`;
  out += `export const PROTOCOL_MINOR = ${registry.protocol.minor};\n\n`;
  out += `export type PagedAddr = ${union(addrs)};\n\n`;
  out += `export type PagedFlag = ${union(flags)};\n\n`;
  out += `export interface PagedCommand {\n`;
  out += `  readonly id: number;\n`;
  out += `  readonly get: boolean;\n`;
  out += `  readonly set: boolean;\n`;
  out += `  readonly addr: PagedAddr;\n`;
  out += `  // GET reply bytes; 'var' when variable, null when there is no GET.\n`;
  out += `  readonly getLen: number | 'var' | null;\n`;
  out += `  // SET payload bounds; null for BULK commands, whose payload is the whole struct.\n`;
  out += `  readonly setMin: number | null;\n`;
  out += `  readonly setMax: number | null;\n`;
  out += `  readonly flags: readonly PagedFlag[];\n`;
  out += `  // Firmware build condition; null when always built.\n`;
  out += `  readonly build: string | null;\n`;
  out += `}\n\n`;

  out += `// Result codes SYS.LAST_RESULT reports.\n`;
  out += `export const VcResult = {\n`;
  for (const [name, code] of Object.entries(legacy.vc_results)) out += `  ${name}: ${hex(code, 2)},\n`;
  out += `} as const;\n\n`;

  out += `export const PagedPage = {\n`;
  for (const p of registry.pages) {
    out += docComment(p.doc, '  ');
    out += `  ${p.mnemonic}: { page: ${hex(p.page, 2)}, revision: ${p.revision} },\n`;
  }
  out += `} as const;\n\n`;

  out += `export const PagedCmd = {\n`;
  for (const p of registry.pages) {
    out += `  ${p.mnemonic}: {\n`;
    for (const c of p.commands) {
      const getLen = c.get_len === null ? 'null' : typeof c.get_len === 'number' ? String(c.get_len) : str(c.get_len);
      const bulk = c.flags.includes('BULK');
      const fields = [
        `id: ${hex(c.id, 4)}`,
        `get: ${c.get}`,
        `set: ${c.set}`,
        `addr: ${str(c.addr)}`,
        `getLen: ${getLen}`,
        `setMin: ${bulk ? 'null' : c.set_min}`,
        `setMax: ${bulk ? 'null' : c.set_max}`,
        `flags: [${c.flags.map(str).join(', ')}]`,
        `build: ${c.build === null ? 'null' : str(c.build)}`,
      ];
      out += docComment(c.doc, '    ');
      out += `    ${c.name}: { ${fields.join(', ')} },\n`;
    }
    out += `  },\n`;
  }
  out += `} as const satisfies Record<keyof typeof PagedPage, Record<string, PagedCommand>>;\n`;
  return out;
}

const args = process.argv.slice(2);
const mode = args[0] ?? 'generate';
if (!['generate', '--check', '--fetch'].includes(mode) || args.length > (mode === '--fetch' ? 2 : 1)) {
  fail(`unknown arguments: ${args.join(' ')} (expected none, --check, or --fetch SHA)`);
}
if (mode === '--fetch') await vendor(args[1] ?? '');

const read = (file) => JSON.parse(readFileSync(resolve(VENDOR, file), 'utf8'));
const registry = read('dspi_commands.json');
const legacy = read('legacy_map.json');
validate(registry, legacy);
const text = render(registry, legacy, read('SOURCE.json'));

if (mode === '--check') {
  let current = '';
  try { current = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n'); } catch { /* missing counts as stale */ }
  if (current !== text) fail('src/protocol/paged.gen.ts is stale; run `npm run gen:paged`');
  console.log('gen-paged: paged.gen.ts is current');
} else {
  writeFileSync(OUT, text);
  const count = registry.pages.reduce((n, p) => n + p.commands.length, 0);
  console.log(`gen-paged: wrote ${count} commands on ${registry.pages.length} pages`);
}
